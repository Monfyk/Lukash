def find_city(query: str):
    """Пошук міста за кодом або назвою (укр/англ)."""
    q = (query or "").strip().lower()
    if not q:
        return None
    if q.upper() in BY_CODE:
        return BY_CODE[q.upper()]
    for c in BY_CODE.values():
        if q in (c["name"].lower(), c["en"].lower()):
            return c
    for c in BY_CODE.values():
        if c["name"].lower().startswith(q) or c["en"].lower().startswith(q):
            return c
    return None
